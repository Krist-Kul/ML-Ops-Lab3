"""Write constraints-lab1.txt: the versions requirements.txt already resolved, without hashes.

    python scripts/derive_constraints.py

The serving lock is compiled against this file, so serving and training cannot disagree
about a shared dependency — the failure mode being an image that passes CI on one
scikit-learn and unpickles the model under another. It also keeps the compile finite:
unconstrained, `pip-compile --generate-hashes` explores every candidate version of numpy,
pandas, scipy and scikit-learn and downloads every wheel of each to hash it.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE, OUT = ROOT / "requirements.txt", ROOT / "constraints-lab1.txt"

pins = [m.group(0) for line in SOURCE.read_text().splitlines()
        if (m := re.match(r"^[A-Za-z0-9][A-Za-z0-9._-]*==[^\s\\]+", line))]
OUT.write_text(
    f"# Generated by scripts/derive_constraints.py from {SOURCE.name}. Do not edit.\n"
    + "\n".join(pins) + "\n"
)
print(f"wrote {OUT.name}: {len(pins)} pins")
